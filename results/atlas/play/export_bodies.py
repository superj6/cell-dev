"""Export the 8 CATCH bodies of the Spiking Tissue Atlas for the browser engine (lifesim.js), plus ground truth.

Run from the repository root (read-only use of the repo):

    PYTHONPATH=. nice -n 10 .venv/bin/python <play>/export_bodies.py bodies            # bodies.json (+ kernel truth)
    PYTHONPATH=. nice -n 10 .venv/bin/python <play>/export_bodies.py ref <body index>   # reference truth of one body
    PYTHONPATH=. nice -n 10 .venv/bin/python <play>/export_bodies.py merge              # truth.json

bodies.json holds everything lifesim.js needs: per body the packed genome row (V3.pack_genomes, GRN mode) or the
program row (V3.pack_program) and initial body (program mode), its world vector (LIFE_ABI.md 4.7, 66 keys, by name),
the hexprism lattice tables (4.3), the world presets, prices and the drag table pow(n, drag_exp) for n < 4096
(glibc's pow, so the engine's drag is bitwise the kernel's).

truth.json holds, per body, 8 standard-world lives on fresh seeds (analysis.fresh_seeds(8, 39_100_000)):
- from the C kernel (build.run through the body's .run, raster on): the full ABI-3 ledger (57 columns, repr), the
  5 hashes, the raster's total count and its first 2,000 (t, uid) pairs;
- from the pure-Python reference (bitwise equal to the kernel): the dot and target positions at the left limit of
  t = 100, 200, ..., 1000 (the samples of LIFE_ABI.md 9.7.6), and the reference's F as a cross-check.
"""
from __future__ import annotations

import json
import math
import sys
import time
from pathlib import Path

import numpy as np

from src.life import analysis, spec
from src.life import probe as P
from src.life import reference as R

V3 = spec.V3
HERE = Path(__file__).resolve().parent
SEEDS = analysis.fresh_seeds(8, seed0=39_000_000 + 100_000 * 1)
GRN_RUNS = ("speck_lmax4_hexprism_sex_s5", "speck_lmax4_hexprism_sex_s4", "speck_lmax4_hexprism_sex_s2",
            "speck_lmax4_hexprism_sex_s6", "speck_lmax4_hexprism_sex_s7", "lmax4_hexprism_sex_s5")
HAND = ("reflex@hollow3", "router@ring4")
RASTER_N = 2000
DOT_TIMES = tuple(float(t) for t in range(100, 1001, 100))
DRAG_N = 4096


def bodies():
    out = []
    for run in GRN_RUNS:
        org, preset = P.load(run)
        out.append((run, org, preset))
    for name in HAND:
        org, preset = P.hand(name)
        out.append((name, org, preset))
    return out


def hex64(u) -> str:
    return format(int(u) & spec.MASK64, "016x")


def export_abi(abi=3):
    """Browser exports are explicitly ABI 3 by default; visibility requires ABI 4."""
    if abi in (3, spec.V3):
        return spec.V3
    if abi in (4, spec.V4):
        return spec.V4
    raise ValueError("browser exports support ABI 3 or 4")


def world_dict(w: spec.World, abi=3) -> dict:
    contract = export_abi(abi)
    contract.validate_world(w)  # Do not silently discard enabled ABI-4 visibility fields.
    return {k: float(getattr(w, k)) for k in contract.WORLD_KEYS}


def body_record(org, w: spec.World, *, name=None, preset=None, abi=3) -> dict:
    """Export one unchanged organism and an explicit world without simulating or writing files."""
    contract = export_abi(abi)
    record = dict(name=name or org.name, abi=contract.version, preset=preset or w.name,
                  world=world_dict(w, contract), world_vec=[float(x) for x in contract.pack_world(w)],
                  about=getattr(org, "about", ""))
    if P.is_program(org):
        record.update(mode="program", program=[float(x) for x in np.asarray(org.program, np.float64)],
                      cells=[[int(v) for v in c] for c in org.cells])
    else:
        gt = contract.pack_genomes(np.asarray(org.genome)[None], w.lattice)[0]
        record.update(mode="grn", genome=[float(x) for x in gt])
    return record


def lattice() -> dict:
    lat, unit = V3.lattice_tables("hexprism")
    lat = [int(x) for x in lat]
    D = lat[1]
    cols = [lat[2 + i * D: 2 + (i + 1) * D] for i in range(7)]
    names = ("off_a", "off_b", "off_z", "back", "prev", "next", "rot")
    d = dict(kind="hexprism", code=lat[0], D=D, **dict(zip(names, cols)))
    d["unit"] = [[float(v) for v in row] for row in unit]
    return d


def export_bodies(with_kernel: bool = True) -> None:
    doc = dict(
        about="CATCH bodies for lifesim.js (LIFE_ABI.md ABI 3); generated by export_bodies.py",
        abi=3, knobs=list(V3.KNOBS), world_keys=list(V3.WORLD_KEYS), ledger=list(V3.LEDGER),
        hashes=list(V3.HASHES), flags=dict(V3.FLAGS), lattice=lattice(),
        genome_slices={k: list(v) for k, v in V3.GENOME_SLICES.items()},
        program=dict(rows=list(spec.PROGRAM_ROWS), scalars=list(spec.PROGRAM_SCALARS), P=V3.P),
        presets={name: world_dict(spec.PRESETS[name]) for name in ("catch_v1_l4", "catch_speck_l4")},
        prices={name: dict(R_cap=spec.PRESETS[name].R_cap, c_miss=spec.PRESETS[name].c_miss,
                           c_rec=spec.PRESETS[name].c_rec, **spec.COSTS)
                for name in ("catch_v1_l4", "catch_speck_l4")},
        seeds=SEEDS, bodies=[])
    drag_exps = {spec.PRESETS[p].drag_exp for p in doc["presets"]}
    assert len(drag_exps) == 1
    de = drag_exps.pop()
    doc["drag"] = dict(drag_exp=de, table=[0.0] + [math.pow(float(n), de) for n in range(1, DRAG_N)])
    for name, org, preset in bodies():
        w = org.world(preset)
        doc["bodies"].append(body_record(org, w, name=name, preset=preset))
    (HERE / "bodies.json").write_text(json.dumps(doc, separators=(",", ":")))
    print("wrote", HERE / "bodies.json", (HERE / "bodies.json").stat().st_size, "bytes")
    if with_kernel:
        kernel_truth()


def kernel_truth() -> None:
    truth = dict(seeds=SEEDS, raster_n=RASTER_N, dot_times=DOT_TIMES, bodies=[])
    for name, org, preset in bodies():
        t = time.time()
        lv = org.run(SEEDS, threads=4, preset=preset, raster_cap=RASTER_N, fate_cap=0)
        lives = []
        for i, s in enumerate(SEEDS):
            rt, ru = lv.spikes(i)
            lives.append(dict(seed=s, ledger=[repr(float(x)) for x in lv.ledger[i]],
                              hashes=[hex64(h) for h in lv.hashes[i]], raster_total=int(lv.raster_n[i]),
                              raster_t=[repr(float(x)) for x in rt], raster_uid=[hex64(u) for u in ru]))
        truth["bodies"].append(dict(name=name, preset=preset, lives=lives))
        print(f"kernel {name}: {time.time() - t:.2f}s", flush=True)
    (HERE / "truth_kernel.json").write_text(json.dumps(truth, separators=(",", ":")))


class _DotAcct(R._Accountant):
    """The reference accountant, recording the dot and the target at the samples t = 100, ..., 1000."""

    def __init__(self, life):
        self.dots = []
        super().__init__(life)

    def sample(self, c: float) -> None:
        super().sample(c)
        if c in DOT_TIMES:
            X, Y = self.dot_at(c)
            x0, y0 = self.blob_at(0, c)
            self.dots.append([repr(c), repr(X), repr(Y), repr(x0), repr(y0)])


class _DotLife(R._Life):
    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self.acct = _DotAcct(self)  # a fresh accountant (the base one has done nothing but start the world)


def ref_truth(ix: int) -> None:
    name, org, preset = bodies()[ix]
    w = org.world(preset)
    wv, latd, gt, prog, cells = P._inputs(org, w)
    lives = []
    for s in SEEDS:
        t = time.time()
        life = _DotLife(wv, latd, gt, prog, cells, (int(s), 0, 0, 0), 0, 0, False)
        res = life.run()
        lives.append(dict(seed=s, F=repr(float(res["F"])), hashes=[hex64(h) for h in res.hashes],
                          dots=life.acct.dots))
        print(f"ref {name} seed {s}: F {res['F']:.6f} {time.time() - t:.1f}s", flush=True)
    (HERE / f"truth_ref_{ix}.json").write_text(json.dumps(dict(name=name, lives=lives), separators=(",", ":")))


def merge() -> None:
    truth = json.loads((HERE / "truth_kernel.json").read_text())
    n_same = 0
    for ix, b in enumerate(truth["bodies"]):
        p = HERE / f"truth_ref_{ix}.json"
        if not p.exists():
            print("missing reference truth for", b["name"])
            continue
        ref = json.loads(p.read_text())
        assert ref["name"] == b["name"]
        for lv, rl in zip(b["lives"], ref["lives"]):
            assert lv["seed"] == rl["seed"]
            lv["ref_F"] = rl["F"]
            lv["ref_hashes"] = rl["hashes"]
            lv["dots"] = rl["dots"]
            # the kernel ran with a raster (its overflow status bit enters the "all" hash), the reference without:
            # compare F and the record families spikes, fate, chem and world
            k_F = lv["ledger"][V3.L["F"]]
            if k_F != rl["F"] or lv["hashes"][1:] != rl["hashes"][1:]:
                print(f"kernel != reference: {b['name']} seed {lv['seed']}: {k_F} {rl['F']}")
            else:
                n_same += 1
    print(f"kernel = reference (F and the spikes, fate, chem, world hashes) in {n_same} lives")
    (HERE / "truth.json").write_text(json.dumps(truth, separators=(",", ":")))
    print("wrote", HERE / "truth.json", (HERE / "truth.json").stat().st_size, "bytes")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "bodies"
    if cmd == "bodies":
        export_bodies()
    elif cmd == "ref":
        ref_truth(int(sys.argv[2]))
    elif cmd == "merge":
        merge()
    else:
        raise SystemExit(f"unknown command {cmd}")
